static void UART_Send_String(const char *text)
{
  uint16_t length = 0U;

  while (text[length] != '\0')
  {
    length++;
  }

  if (length > 0U)
  {
    (void)HAL_UART_Transmit(&huart1, (uint8_t *)text, length,
                            HAL_MAX_DELAY);
  }
}

static void UART_Send_Number(uint32_t number)
{
  char digits[10];
  uint8_t count = 0U;

  if (number == 0U)
  {
    UART_Send_String("0");
    return;
  }

  while ((number > 0U) && (count < sizeof(digits)))
  {
    digits[count] = (char)('0' + (number % 10U));
    number /= 10U;
    count++;
  }

  while (count > 0U)
  {
    count--;
    (void)HAL_UART_Transmit(&huart1, (uint8_t *)&digits[count], 1U,
                            HAL_MAX_DELAY);
  }
}

static void UART_Print_10ms_Time(void)
{
  uint32_t timestamp = SCH_Get_Time_MS();

  UART_Send_String("T=");
  UART_Send_Number(timestamp);
  UART_Send_String("\r\n");
}

